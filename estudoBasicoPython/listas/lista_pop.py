# pop
# similar ao remove, porem remove a posicao escolhida e guarda o elemento removido

numeros = [1, 2, 3, 4, 5]
print(numeros)

nRemovido = numeros.pop(3) # remove o numero 4 e guarda em "nRemovido"
print(nRemovido)
print(numeros)

comidas = ["banana", "chocolate", "bolo", 'macarrao', "batata"]
print(comidas)

cRemovido = comidas.pop(0) # remove a banana e guarda em "cRemovido"
print(cRemovido)
print(comidas)
