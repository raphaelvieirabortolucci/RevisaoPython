# slice
# [inicio:fim:passo]
# inicio: vai selecionar a posicao da letra desejada
# fim: vai selecionar a posicao de letra final
# passo: vai definir a quantidade de casa que vai ser pulada

texto = "palavraGrande"

print(texto[2])      # l segunda letra do "0" ao "2"
print(texto[0:13])   # palavraGrande do "0" ao "13"
print(texto[0:7])    # palavra "0" ao "7"
print(texto[7:])     # Grande "7" ate o fim
print(texto[:5])     # palav "0" ao "5"
print(texto[-3:])    # nde ultimas 3 letras
